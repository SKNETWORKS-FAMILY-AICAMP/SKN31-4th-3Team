"""
scripture/books.py
────────────────────────────────────────────────────────────────────────
성경 66권의 약어·정식명·정경 순서.

★ 왜 필요한가
  data/bible_structured.json 은 책을 약어로만 담고 있다("창", "요일").
  화면에는 "창세기 1:1" 로 나가야 하고, 목록은 정경 순서로 정렬돼야
  한다. 창세기 다음이 출애굽기지 갈라디아서가 아니다.

★ 순서를 알파벳순이나 가나다순으로 두지 않는다
  "갈라디아서 → 창세기 → 고린도전서" 로 늘어놓으면 성경을 아는 사람에게는
  즉시 어색하고, 모르는 사람에게는 아무 의미가 없다. 정경 순서가 유일하게
  기대되는 순서다.

★ 이 표가 진실의 원본이다
  큐레이션 구절(scripture/fixtures/verses.json)에도 book_name 이 들어
  있지만 46권분뿐이다. 성경전서를 적재하려면 66권이 다 필요하다.
  앞으로 두 곳이 어긋나지 않도록 테스트로 묶어 둔다.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class Book:
    code: str
    name: str
    #: 1부터. 정경 순서다.
    order: int
    #: 구약인가.
    old: bool


def _build() -> tuple[Book, ...]:
    old = [
        ("창", "창세기"), ("출", "출애굽기"), ("레", "레위기"), ("민", "민수기"),
        ("신", "신명기"), ("수", "여호수아"), ("삿", "사사기"), ("룻", "룻기"),
        ("삼상", "사무엘상"), ("삼하", "사무엘하"), ("왕상", "열왕기상"),
        ("왕하", "열왕기하"), ("대상", "역대상"), ("대하", "역대하"),
        ("스", "에스라"), ("느", "느헤미야"), ("에", "에스더"), ("욥", "욥기"),
        ("시", "시편"), ("잠", "잠언"), ("전", "전도서"), ("아", "아가"),
        ("사", "이사야"), ("렘", "예레미야"), ("애", "예레미야애가"),
        ("겔", "에스겔"), ("단", "다니엘"), ("호", "호세아"), ("욜", "요엘"),
        ("암", "아모스"), ("옵", "오바댜"), ("욘", "요나"), ("미", "미가"),
        ("나", "나훔"), ("합", "하박국"), ("습", "스바냐"), ("학", "학개"),
        ("슥", "스가랴"), ("말", "말라기"),
    ]
    new = [
        ("마", "마태복음"), ("막", "마가복음"), ("눅", "누가복음"), ("요", "요한복음"),
        ("행", "사도행전"), ("롬", "로마서"), ("고전", "고린도전서"),
        ("고후", "고린도후서"), ("갈", "갈라디아서"), ("엡", "에베소서"),
        ("빌", "빌립보서"), ("골", "골로새서"), ("살전", "데살로니가전서"),
        ("살후", "데살로니가후서"), ("딤전", "디모데전서"), ("딤후", "디모데후서"),
        ("딛", "디도서"), ("몬", "빌레몬서"), ("히", "히브리서"), ("약", "야고보서"),
        ("벧전", "베드로전서"), ("벧후", "베드로후서"), ("요일", "요한일서"),
        ("요이", "요한이서"), ("요삼", "요한삼서"), ("유", "유다서"),
        ("계", "요한계시록"),
    ]
    books = []
    for i, (code, name) in enumerate(old + new, start=1):
        books.append(Book(code=code, name=name, order=i, old=i <= len(old)))
    return tuple(books)


BOOKS: tuple[Book, ...] = _build()

BY_CODE: dict[str, Book] = {b.code: b for b in BOOKS}


def name_of(code: str) -> str:
    """
    약어 → 정식명.

    ★ 모르는 약어면 그대로 돌려준다.
      번역본이 바뀌어 새 약어가 들어와도 적재가 멈추지 않는다.
      "창세기 1:1" 대신 "창 1:1" 이 나올 뿐, 데이터는 들어간다.
    """
    book = BY_CODE.get(code)
    return book.name if book else code


def order_of(code: str) -> int:
    """
    정경 순서. 모르는 약어는 맨 뒤로 보낸다.

    0 을 주면 창세기보다 앞에 서고, 목록 맨 위가 정체불명이 된다.
    """
    book = BY_CODE.get(code)
    return book.order if book else 999


def ref(code: str, chapter: int, verse: int) -> str:
    """화면에 그대로 쓰는 출처 문자열."""
    return f"{name_of(code)} {chapter}:{verse}"
