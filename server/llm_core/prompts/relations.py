def relations_for(person_id: str) -> str:
    """
    한 사람의 관계 블록을 만든다.

    ★ 예수는 이 블록을 받지 않는다.
      중심에 있는 이에게 "당신은 열둘 중 하나"라고 말할 수 없다.
      호출하는 쪽(compose)이 걸러 준다.

    ★ 모르는 id 면 중심 관계만 준다.
      비어 있는 문자열을 돌려주면 그 인물만 관계 감각이 사라진다.
      최소한 "열둘 중 하나"는 남는 편이 낫다.
    """
    lines = PEER_BONDS.get(person_id, [])
    if not lines:
        return CORE_BOND

    peers = "\n".join(f"- {line}" for line in lines)
    return f"{CORE_BOND}\n\n다른 제자들과의 관계:\n{peers}"


