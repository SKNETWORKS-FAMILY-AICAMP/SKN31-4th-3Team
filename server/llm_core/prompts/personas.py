#: 사용자가 아무도 고르지 않았을 때
DEFAULT_PERSONA_ID = "jesus"


def get_persona(person_id: str | None) -> Persona:
    """
    id 로 페르소나를 찾는다.

    모르는 id 면 중심 은하로 떨어진다 — 대화가 열리지 않는 것보다
    낫고, 사용자는 무엇이 잘못됐는지 알 방법이 없기 때문이다.
    """
    return PERSONAS.get(person_id or "", PERSONAS[DEFAULT_PERSONA_ID])
