"""
llm_core/prompts/personas.py
────────────────────────────────────────────────────────────────────────
열셋의 페르소나.

★ 화면과 같은 id 를 쓴다
  frontend/src/data/disciples.ts 의 13개 은하와 1:1 이다.
  id·이름·역할이 어긋나면 사용자가 요한 은하를 눌렀는데 마태가 답한다.
  테스트가 이 정합성을 지킨다 (tests/test_personas.py).

★ 근거를 나눠 적는다
  - `scripture`: 복음서에 적힌 것
  - `tradition`: 오랜 전승 — 사실로 단정하지 않는다
  성경에 없는 것을 성경인 양 말하지 않기 위해 처음부터 갈라 둔다.

★ 말투는 어미가 아니라 리듬으로 만든다
  전원 현대 한국어 존댓말이다. "…하느니라" 같은 옛 어미는 쓰지 않는다.
  차이는 문장 길이, 먼저 묻는지 먼저 공감하는지, 비유를 쓰는지에서 난다.
  (common.py 의 FORMAT 참조)

★ 강점만 적지 않는다
  각 인물에게 `caution` 을 둔다. 성격이 상담에서 해롭게 작동할 수 있는
  지점이다. 이걸 안 적으면 "열심 있는 시몬"이 사용자를 몰아붙인다.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Persona:
    """한 인물의 페르소나 정의."""

    id: str
    name: str
    #: 화면에 표시되는 한 마디 (disciples.ts 의 role 과 같아야 한다)
    role: str
    mbti: str

    #: 복음서에 적힌 것
    scripture: list[str]
    #: 오랜 전승 — 사실로 단정하지 않는다
    tradition: list[str] = field(default_factory=list)

    #: 어떤 사람인가 (2~4문장)
    character: str = ""
    #: 어떻게 말하는가
    voice: str = ""
    #: 상담에서 무엇을 잘하는가
    strength: str = ""
    #: 이 성격이 해롭게 작동할 수 있는 지점
    caution: str = ""
    #: 첫 인사 (대화를 열 때 쓴다)
    greeting: str = ""


