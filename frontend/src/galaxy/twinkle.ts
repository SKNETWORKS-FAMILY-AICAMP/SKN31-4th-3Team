/*
 * galaxy/twinkle.ts
 * ───────────────────────────────────────────────────────────────────────
 * 별마다 다른 호흡으로 밝기가 흔들린다.
 *
 * ★ 왜 필요한가
 *   모든 별이 같은 밝기로 고정돼 있으면 하늘이 아니라 전구판이 된다.
 *   실제 별빛이 흔들리는 이유는 대기의 굴절이고, 그래서 별마다 다르고
 *   순간마다 다르다. 우리가 만들려는 것은 정확한 물리가 아니라
 *   "저것은 켜 둔 조명이 아니라 먼 빛" 이라는 감각이다.
 *
 * ★ 상태를 두지 않는다
 *   별 하나마다 현재 밝기를 들고 있으면 2,652개짜리 배열이 하나 더 늘고,
 *   매 프레임 그것을 갱신해야 한다. 대신 시간과 인덱스만으로 값을
 *   계산한다 — 순수 함수라 프레임을 건너뛰어도 어긋나지 않고,
 *   되감아도 같은 값이 나온다.
 *
 * ★ 주기가 서로 나누어떨어지지 않게 한다
 *   주기를 몇 개만 쓰면 별들이 무리 지어 함께 깜빡인다. 눈은 그 동기화를
 *   아주 잘 알아채고, 그러면 "반짝인다" 가 아니라 "점멸한다" 로 보인다.
 *   무리수에 가까운 배수를 섞어 위상이 다시 만나지 않게 한다.
 */

/** 밝기가 흔들리는 폭. 0.22 면 78%~100% 사이를 오간다. */
export const TWINKLE_DEPTH = 0.22;

/**
 * 가장 짧은 주기와 가장 긴 주기 (초).
 *
 * ★ 1초 아래로 내려가지 않는다.
 *   그보다 빠르면 별이 아니라 신호등처럼 보인다. 실제로 눈에 띄는
 *   별의 흔들림은 느리고 불규칙하다.
 */
const MIN_PERIOD = 2.4;
const MAX_PERIOD = 7.8;

/**
 * 어두운 별이 더 많이 흔들린다.
 *
 * ★ 실제로도 그렇다.
 *   밝은 별은 광량이 많아 흔들림이 상대적으로 작게 느껴지고, 어두운
 *   별은 같은 양의 흔들림이 훨씬 크게 보인다. 화면에서도 이 비율이
 *   맞아야 밝은 별이 "중심" 으로 읽힌다.
 */
const DIM_EXTRA = 0.6;

/**
 * 인덱스를 0~1 의 고른 값으로 흩는다.
 *
 * ★ 난수를 쓰지 않는다.
 *   버퍼를 하나 더 만들지 않으려면 인덱스에서 바로 뽑아야 한다.
 *   황금비 곱의 소수부는 어떤 개수에서도 고르게 퍼진다 —
 *   i * 0.618… 의 소수부가 그것이다.
 */
function scatter(i: number, salt: number): number {
  const v = (i + 1) * 0.6180339887498949 + salt * 0.7548776662466927;
  return v - Math.floor(v);
}

/**
 * 이 순간 이 별의 밝기 배수.
 *
 * @param index 별 번호
 * @param time  경과 시간 (초)
 * @param magnitude 0~1. 어두운 별일수록 더 흔들린다.
 * @returns 0.5 ~ 1.0 근처의 배수. 원래 alpha 에 곱해 쓴다.
 *
 * ★ 두 파동을 겹친다.
 *   사인 하나면 규칙적으로 뛰는 맥박처럼 보인다. 주기가 다른 둘을
 *   겹치면 마루가 매번 다른 자리에 오고, 그래야 불규칙해 보인다.
 */
export function twinkleAt(index: number, time: number, magnitude: number): number {
  const a = scatter(index, 0);
  const b = scatter(index, 1);

  const period = MIN_PERIOD + a * (MAX_PERIOD - MIN_PERIOD);
  // 두 번째 파동은 조금 더 느리게 — 배수를 정수로 두면 둘이 같이 만난다
  const slow = period * 1.618;

  const wave =
    Math.sin(((time / period) + b) * Math.PI * 2) * 0.65 +
    Math.sin(((time / slow) + a) * Math.PI * 2) * 0.35;

  // 어두운 별에 흔들림을 더 준다
  const depth = TWINKLE_DEPTH * (1 + (1 - magnitude) * DIM_EXTRA);

  // wave 는 -1~1. 위쪽을 1 에 붙여 두어 "어두워졌다 돌아온다" 로 읽히게 한다.
  return 1 - depth * (0.5 - wave * 0.5);
}
